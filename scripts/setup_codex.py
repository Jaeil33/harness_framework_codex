"""Register project-local Codex skills and hooks. Run outside a read-only agent sandbox."""
import argparse
import base64
import copy
from pathlib import Path
import shlex
import sys

from harness_common import ROOT, HarnessError, configure_stdio, inside, load_config, read_json, resolve_command, run_process, write_json
from hooks import find_dcg

SKILLS = ("harness", "harness-review")
MESSAGES = {"pre-tool": "Harness: command guard", "stop": "Harness: verification"}


def build_hooks(root, python, dcg):
    root = Path(root).resolve()
    config = load_config(root)
    events = {}
    for mode, event in (("pre-tool", "PreToolUse"), ("stop", "Stop")):
        argv = [str(python), "-B", "-X", "utf8", str(root / "scripts/hooks.py"), mode]
        if mode == "pre-tool":
            argv.extend(["--dcg", str(dcg)])
        # Use a real interpreter, without relying on PS execution policy or shell quoting of prompts.
        powershell = "& " + " ".join("'" + arg.replace("'", "''") + "'" for arg in argv)
        encoded = base64.b64encode(powershell.encode("utf-16-le")).decode("ascii")
        handler = {"type": "command", "command": shlex.join(argv),
                   "commandWindows": f"powershell.exe -NoProfile -NonInteractive -EncodedCommand {encoded}",
                   "timeout": 15 if mode == "pre-tool" else config["check_timeout_seconds"] * len(config["verification_commands"]) + 15,
                   "statusMessage": MESSAGES[mode]}
        group = {"hooks": [handler]}
        if mode == "pre-tool":
            group["matcher"] = "Bash|PowerShell|exec_command|shell|shell_command"
        events[event] = [group]
    return {"description": "Codex harness project hooks; generated by scripts/setup_codex.py", "hooks": events}


def merge_hooks(existing, generated):
    result = copy.deepcopy(existing)
    if not isinstance(result, dict) or not isinstance(result.get("hooks", {}), dict):
        raise HarnessError("Existing .codex/hooks.json has an invalid hooks object")
    result.setdefault("hooks", {})
    for event, groups in generated["hooks"].items():
        kept = []
        existing_groups = result["hooks"].get(event, [])
        if not isinstance(existing_groups, list):
            raise HarnessError(f"Invalid existing {event} hook list")
        for group in existing_groups:
            if not isinstance(group, dict) or not isinstance(group.get("hooks"), list):
                raise HarnessError(f"Invalid existing {event} hook group")
            if any(not isinstance(h, dict) for h in group["hooks"]):
                raise HarnessError(f"Invalid existing {event} hook handler")
            handlers = [h for h in group["hooks"] if h.get("statusMessage") not in MESSAGES.values()]
            if handlers:
                kept.append({**group, "hooks": handlers})
        result["hooks"][event] = kept + groups
    result.setdefault("description", generated["description"])
    return result


def install(root=ROOT, *, dcg=None, check=False, update_skills=False):
    root = Path(root).resolve()
    guard = find_dcg(dcg)
    generated = build_hooks(root, sys.executable, guard)
    destination = inside(root, ".codex/hooks.json")
    existing = read_json(destination) if destination.exists() else {}
    merged = merge_hooks(existing, generated)
    copies = []
    for name in SKILLS:
        source = inside(root, f"skills/{name}/SKILL.md")
        target = inside(root, f".agents/skills/{name}/SKILL.md")
        data = source.read_bytes()
        if target.exists() and target.read_bytes() != data and not update_skills:
            raise HarnessError(f"Existing skill differs: {target}. Review it before using --update-skills")
        copies.append((target, data))
    installed = destination.exists() and existing == merged and all(p.exists() and p.read_bytes() == data for p, data in copies)
    if not check:
        write_json(destination, merged)
        for target, data in copies:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        installed = True
    return {"installed": installed, "dcg": str(guard), "hooks": str(destination),
            "skills": [str(p) for p, _ in copies]}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Inspect prerequisites and registration without writing files")
    parser.add_argument("--dcg", help="Absolute path to the dcg executable")
    parser.add_argument("--update-skills", action="store_true", help="Replace registered skills with the reviewed source versions")
    args = parser.parse_args(argv)
    try:
        codex = resolve_command(["codex"])
        version = run_process([*codex, "--version"], cwd=ROOT, timeout=15)
        if version.returncode:
            raise HarnessError(f"Codex cannot start: {version.stderr}")
        print(version.stdout.strip())
        result = install(dcg=args.dcg, check=args.check, update_skills=args.update_skills)
        print(f"dcg: {result['dcg']}")
        print(f"Registration: {'installed' if result['installed'] else 'pending'}")
        print(f"Hooks: {result['hooks']}")
        for name in SKILLS:
            print(f"Skill: ${name}")
        if args.check and not result["installed"]:
            print("Run python scripts/setup_codex.py in your local terminal to register skills and hooks.")
        print("Restart Codex in this project and use /hooks to review/trust the generated hooks. Trust is not granted by this installer.")
        return 0
    except (HarnessError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    configure_stdio()
    raise SystemExit(main())
